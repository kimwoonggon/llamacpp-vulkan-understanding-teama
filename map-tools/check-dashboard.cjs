const { chromium } = require('C:/Users/gerard/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs=require('node:fs');
const assert=require('node:assert/strict');
(async()=>{
  const state=JSON.parse(fs.readFileSync('D:/llama-vulkan-lab/map-tools/dashboard-state.json','utf8').replace(/^\uFEFF/,''));
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1536,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(state.url);await page.waitForTimeout(3500);
  await page.getByRole('button',{name:'다시 보지 않기',exact:true}).click();
  assert((await page.locator('body').innerText()).includes('22 nodes'));
  await page.screenshot({path:'D:/llama-vulkan-lab/map-tools/dashboard-overview.png'});
  const uri=new URL(state.url);const query=uri.search;
  const graph=await (await page.request.get(uri.origin+'/knowledge-graph.json'+query)).json();
  assert.equal(graph.nodes.length,42);assert.equal(graph.edges.length,67);
  const fileResponse=await page.request.get(uri.origin+'/file-content.json'+query+'&path='+encodeURIComponent('ggml/src/ggml-vulkan/ggml-vulkan.cpp'));
  assert.equal(fileResponse.status(),200);const source=await fileResponse.json();
  assert(source.content.includes('void ggml_vk_mul_mat('));
  await page.getByRole('button',{name:'심층',exact:true}).click();
  await page.getByRole('button',{name:'파일',exact:true}).last().click();
  await page.getByTitle('ggml',{exact:true}).click();
  await page.getByTitle('ggml/src',{exact:true}).click();
  await page.getByTitle('ggml/src/ggml-vulkan',{exact:true}).click();
  await page.getByTitle('ggml/src/ggml-vulkan/ggml-vulkan.cpp - double-click to open',{exact:true}).dblclick();
  await page.waitForTimeout(8000);
  console.log('graph nodes',await page.locator('.react-flow__node').count());
  console.log('graph texts',(await page.locator('.react-flow__node').allTextContents()).slice(0,8));
  console.log('transforms',await page.locator('.react-flow__viewport').getAttribute('style'));
  console.log('node boxes',await page.locator('.react-flow__node').evaluateAll(ns=>ns.map(n=>({id:n.dataset.id,style:n.getAttribute('style'),box:n.getBoundingClientRect().toJSON()}))));
  console.log('controls',await page.locator('.react-flow__controls button').evaluateAll(ns=>ns.map(n=>({title:n.title,label:n.getAttribute('aria-label')}))));
  assert(await page.locator('.react-flow__node').evaluateAll(ns=>ns.some(n=>{const r=n.getBoundingClientRect();return r.top<550&&r.bottom>160&&r.left<1176&&r.right>0})), 'Graph nodes must stay visible above the source panel after selecting a file');
  await page.getByRole('button',{name:/^Cluster A container,/}).click();
  await page.waitForTimeout(2000);
  assert(await page.locator('.react-flow__node').count()>5,'Expanding a native cluster must reveal source nodes');
  assert(await page.locator('pre').count()>0,'Native source panel must render code');
  assert((await page.locator('body').innerText()).includes('ggml/src/ggml-vulkan/ggml-vulkan.cpp'));
  await page.screenshot({path:'D:/llama-vulkan-lab/map-tools/dashboard-preview.png'});
  assert.deepEqual(errors,[]);
  fs.writeFileSync('D:/llama-vulkan-lab/map-tools/dashboard-validation.json',JSON.stringify({passed:true,viewerVersion:'2.9.8',projectRoot:state.projectRoot,nodes:graph.nodes.length,edges:graph.edges.length,sourcePanel:true,sourceFile:source.path,sourceBytes:source.sizeBytes,scope:'12 selected source files',pageErrors:errors},null,2));
  await browser.close();console.log('Native dashboard graph and Vulkan source panel verified.');
})().catch(e=>{console.error(e);process.exit(1)});
